#!/usr/bin/env python3
"""
run_benchmark.py — runs the LGPC-BC detector
(src/detector/*, untouched) against a benchmark generated by
generate_benchmark.py, and writes raw per-case results for later,
SEPARATE calibration of beta/tau.

This script does NOT:
  - change B, tau, beta, or any other detector parameter (uses
    detector.config.default_config() exactly as shipped)
  - pick or apply any localization threshold
  - compute or assert any accuracy/precision/recall/F1 figure
  - claim the detector performs well, poorly, or anywhere in between

It only runs the detector once per case and records what came out,
plus simple threshold-free descriptive statistics (mean/median/max of
the detector's own |z_k| map inside vs. outside each case's
ground-truth region) for a human to look at during later calibration.

USAGE
-----
    python src/evaluation/run_benchmark.py \\
        --benchmark-dir path/to/benchmark_output \\
        --output-dir path/to/results_output
"""

from __future__ import annotations

import argparse
import csv
import json
import os
import sys
from typing import Any, Dict, Optional

import cv2
import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

# Unmodified detector code — imported, never edited, never monkeypatched.
from detector.config import default_config
from detector.detector import run_on_image
from detector.preprocessing import InputValidationError


def _descriptive_stats(values: np.ndarray) -> Dict[str, Optional[float]]:
    values = values[~np.isnan(values)]
    if values.size == 0:
        return {"n": 0, "mean": None, "median": None, "max": None}
    return {
        "n": int(values.size),
        "mean": float(np.mean(values)),
        "median": float(np.median(values)),
        "max": float(np.max(values)),
    }


def evaluate_one_case(row: Dict[str, str], detector_output_dir: str, config) -> Dict[str, Any]:
    image_path = row["image_path"]
    mask_path = row["mask_path"]

    result_row: Dict[str, Any] = {
        "case_id": row["case_id"],
        "category": row["category"],
        "subtype": row["subtype"],
        "is_local": row["is_local"],
        "image_level_label": row["image_level_label"],
        "expected_behavior": row["expected_behavior"],
    }

    try:
        detector_result = run_on_image(image_path, detector_output_dir, config)
    except InputValidationError as e:
        result_row["run_status"] = "input_rejected"
        result_row["run_error"] = str(e)
        return result_row
    except Exception as e:  # pragma: no cover - defensive only
        result_row["run_status"] = "error"
        result_row["run_error"] = str(e)
        return result_row

    result_row["run_status"] = "ok"
    result_row["M_image"] = detector_result.image_level_score
    result_row["tau_used"] = config.tau
    result_row["beta_used"] = config.beta
    result_row["decision_flagged"] = detector_result.decision_flagged

    diag = detector_result.diagnostics
    result_row["fraction_blocks_eligible"] = diag.get("fraction_blocks_eligible")
    result_row["residual_r_mad_goodness_of_fit"] = diag.get("residual_r_mad_goodness_of_fit")

    # --- threshold-free localization descriptive stats ---
    raw_map_path = os.path.join(detector_output_dir, "raw_block_consistency_map.npy")
    gt_mask = cv2.imread(mask_path, cv2.IMREAD_UNCHANGED)
    if gt_mask is None:
        result_row["localization_note"] = "ground_truth_mask_unreadable"
        return result_row
    gt_mask_bool = gt_mask.astype(bool)

    if not os.path.isfile(raw_map_path):
        result_row["localization_note"] = "raw_block_consistency_map_missing"
        return result_row

    raw_map = np.load(raw_map_path)
    if raw_map.shape != gt_mask_bool.shape:
        result_row["localization_note"] = "shape_mismatch_between_map_and_mask"
        return result_row

    inside = raw_map[gt_mask_bool]
    outside = raw_map[~gt_mask_bool]

    n_gt_pixels = int(gt_mask_bool.sum())
    n_gt_eligible = int(np.count_nonzero(~np.isnan(inside)))
    result_row["gt_pixels_total"] = n_gt_pixels
    result_row["gt_pixels_eligible"] = n_gt_eligible
    result_row["gt_pixels_eligible_fraction"] = (n_gt_eligible / n_gt_pixels) if n_gt_pixels else None

    inside_stats = _descriptive_stats(inside)
    outside_stats = _descriptive_stats(outside)
    result_row["abs_z_inside_gt_mean"] = inside_stats["mean"]
    result_row["abs_z_inside_gt_median"] = inside_stats["median"]
    result_row["abs_z_inside_gt_max"] = inside_stats["max"]
    result_row["abs_z_inside_gt_n_eligible"] = inside_stats["n"]
    result_row["abs_z_outside_gt_mean"] = outside_stats["mean"]
    result_row["abs_z_outside_gt_median"] = outside_stats["median"]
    result_row["abs_z_outside_gt_max"] = outside_stats["max"]
    result_row["abs_z_outside_gt_n_eligible"] = outside_stats["n"]

    return result_row


def _load_existing_results(results_csv_path: str) -> Dict[str, Dict[str, Any]]:
    """
    Loads any already-completed case results from a prior (possibly
    interrupted) run, keyed by case_id, so main() can resume instead of
    recomputing from scratch. Returns {} if no prior results file exists.
    """
    if not os.path.isfile(results_csv_path):
        return {}
    with open(results_csv_path, newline="") as f:
        rows = list(csv.DictReader(f))
    return {r["case_id"]: r for r in rows if r.get("case_id")}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--benchmark-dir", required=True, help="Directory produced by generate_benchmark.py.")
    parser.add_argument("--output-dir", required=True, help="Directory for raw results (created if missing).")
    parser.add_argument(
        "--limit",
        type=int,
        default=None,
        help="Process at most this many NOT-YET-COMPLETED cases this run, then stop (for chunked/resumable runs).",
    )
    parser.add_argument(
        "--resume",
        action="store_true",
        help="Skip case_ids already present in an existing benchmark_results.csv in --output-dir.",
    )
    parser.add_argument("--tau", type=float, default=None, help="Override decision threshold tau.")
    parser.add_argument("--beta", type=float, default=None, help="Override aggregation percentile beta.")
    parser.add_argument("--n-bins", type=int, default=None, help="Override number of dispersion-curve bins.")
    parser.add_argument("--block-size", type=int, default=None, help="Override block size B.")
    args = parser.parse_args()

    manifest_path = os.path.join(args.benchmark_dir, "benchmark_manifest.csv")
    if not os.path.isfile(manifest_path):
        raise SystemExit(f"[error] benchmark manifest not found: {manifest_path}")

    with open(manifest_path, newline="") as f:
        rows = list(csv.DictReader(f))

    # The frozen, uncalibrated, shipped-default detector configuration.
    # NOT modified in any way for this benchmark run.
    config = default_config()
    for _name, _val in (("tau", args.tau), ("beta", args.beta), ("n_bins", args.n_bins), ("block_size", args.block_size)):
        if _val is not None:
            setattr(config, _name, _val)
    config.validate()
    print("[info] running with default parameters (unmodified):")
    for k, v in config.as_dict().items():
        print(f"    {k:16s} = {v}")

    os.makedirs(args.output_dir, exist_ok=True)
    detector_outputs_root = os.path.join(args.output_dir, "detector_outputs")
    results_csv_path = os.path.join(args.output_dir, "benchmark_results.csv")

    existing_results = _load_existing_results(results_csv_path) if args.resume else {}
    if existing_results:
        print(f"[info] resuming: {len(existing_results)} case(s) already completed, will be kept as-is.")

    results: list = []
    n_newly_run = 0
    for i, row in enumerate(rows):
        case_id = row["case_id"]
        if case_id in existing_results:
            results.append(existing_results[case_id])
            continue
        if args.limit is not None and n_newly_run >= args.limit:
            print(f"[info] --limit {args.limit} reached; stopping early. Re-run with --resume to continue.")
            break
        detector_output_dir = os.path.join(detector_outputs_root, case_id)
        result_row = evaluate_one_case(row, detector_output_dir, config)
        results.append(result_row)
        n_newly_run += 1
        status = result_row.get("run_status")
        m_image = result_row.get("M_image")
        print(f"[{i + 1}/{len(rows)}] {case_id}: status={status} M_image={m_image}")

    # Raw per-case results (no calibration, no accuracy metric computed).
    all_fieldnames: list = []
    for r in results:
        for k in r.keys():
            if k not in all_fieldnames:
                all_fieldnames.append(k)
    with open(results_csv_path, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=all_fieldnames)
        writer.writeheader()
        for r in results:
            writer.writerow(r)

    # A purely descriptive, non-evaluative per-category rollup — averages
    # of the raw numbers above, nothing calibrated or judged.
    def _to_float_or_none(v: Any) -> Optional[float]:
        # Result rows may come either fresh (native float/bool from this
        # run) or reloaded from a prior run's CSV (everything is a str
        # there, including "nan"/"True"/"False"/""). Handle both without
        # changing what is actually reported.
        if v is None or v == "":
            return None
        try:
            f = float(v)
        except (TypeError, ValueError):
            return None
        return None if np.isnan(f) else f

    def _to_bool(v: Any) -> bool:
        if isinstance(v, bool):
            return v
        return str(v).strip().lower() == "true"

    by_category: Dict[str, list] = {}
    for r in results:
        by_category.setdefault(r["category"], []).append(r)

    summary = {}
    for cat, cat_rows in by_category.items():
        ok_rows = [r for r in cat_rows if r.get("run_status") == "ok"]
        m_images = [mv for mv in (_to_float_or_none(r.get("M_image")) for r in ok_rows) if mv is not None]
        n_flagged = sum(1 for r in ok_rows if _to_bool(r.get("decision_flagged")))
        summary[cat] = {
            "n_cases": len(cat_rows),
            "n_run_ok": len(ok_rows),
            "n_flagged_at_current_tau": n_flagged,
            "M_image_values": m_images,
            "note": "Descriptive only. No threshold has been calibrated; "
            "'n_flagged_at_current_tau' reflects the shipped, uncalibrated "
            "tau placeholder, not a validated decision.",
        }

    summary_path = os.path.join(args.output_dir, "benchmark_summary_raw.json")
    with open(summary_path, "w") as f:
        json.dump(
            {
                "config_used": config.as_dict(),
                "all_parameters_are_uncalibrated_placeholders": True,
                "per_category": summary,
                "disclaimer": (
                    "These are raw, uncalibrated results from a small sanity "
                    "benchmark. No accuracy/precision/recall claim is made or "
                    "implied. Use these numbers only as input to a later, "
                    "separate calibration and analysis step."
                ),
            },
            f,
            indent=2,
        )

    print(f"\n[done] raw per-case results: {results_csv_path}")
    print(f"[done] raw per-category rollup: {summary_path}")
    print(f"[done] per-case detector outputs under: {detector_outputs_root}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
